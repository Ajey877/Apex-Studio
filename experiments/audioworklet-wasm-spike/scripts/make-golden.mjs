#!/usr/bin/env node
// Regenerates web/golden.mjs from the pure-JS reference (NOT from the WASM
// output), so the WASM/worklet results are always checked against an
// independently produced value. Only rerun if TEST_VECTOR or the reference
// algorithm intentionally changes.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TEST_VECTOR as TV, generateTestSignal, referenceProcess, sha256OfChannels } from '../web/reference.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = generateTestSignal().map(ch => referenceProcess(ch, TV.gain, TV.coefficients));
const sha = await sha256OfChannels(out);
writeFileSync(join(root, 'web', 'golden.mjs'), `// GENERATED by scripts/make-golden.mjs from the pure-JS reference — do not edit.
// SHA-256 of the reference output (ch0 then ch1, little-endian f32) for TEST_VECTOR.
export const REFERENCE_SHA256 = '${sha}';
`);
console.log(`[spike] reference sha256 ${sha}`);
