#!/usr/bin/env node
// Builds dsp/gain_biquad.wat -> dsp/gain_biquad.wasm and web/wasm-bytes.mjs.
//
//   node scripts/build-wasm.mjs           # (re)build
//   node scripts/build-wasm.mjs --check   # verify committed artifacts are reproducible
//
// Toolchain: wabt (WebAssembly Binary Toolkit) compiled to JS/WASM, npm package
// `wabt` pinned to 1.0.39, Apache-2.0, zero runtime dependencies, no native build
// step and no install scripts. It runs identically on Linux and Windows.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import wabtInit from 'wabt';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const watPath = join(root, 'dsp', 'gain_biquad.wat');
const wasmPath = join(root, 'dsp', 'gain_biquad.wasm');
const bytesModulePath = join(root, 'web', 'wasm-bytes.mjs');
const check = process.argv.includes('--check');

const wabt = await wabtInit();
// Normalize line endings so a Windows checkout (core.autocrlf) builds identical bytes.
const source = readFileSync(watPath, 'utf8').replace(/\r\n/g, '\n');
const parsed = wabt.parseWat('gain_biquad.wat', source, {});
parsed.resolveNames();
parsed.validate();
const { buffer } = parsed.toBinary({ log: false, write_debug_names: false });
parsed.destroy();
const bytes = Buffer.from(buffer);
const sha256 = createHash('sha256').update(bytes).digest('hex');

const bytesModule = `// GENERATED by scripts/build-wasm.mjs from dsp/gain_biquad.wat — do not edit.
// Embedded so the harness never needs fetch() for the binary (fetch of file://
// URLs is not generally available in Chromium/Electron renderers).
export const WASM_SHA256 = '${sha256}';
export const WASM_BYTE_LENGTH = ${bytes.length};
export const WASM_BASE64 = '${bytes.toString('base64')}';
export function wasmBytes() {
  const bin = atob(WASM_BASE64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}
`;

if (check) {
  const problems = [];
  if (!existsSync(wasmPath) || !readFileSync(wasmPath).equals(bytes)) problems.push('dsp/gain_biquad.wasm');
  if (!existsSync(bytesModulePath) || readFileSync(bytesModulePath, 'utf8').replace(/\r\n/g, '\n') !== bytesModule) {
    problems.push('web/wasm-bytes.mjs');
  }
  if (problems.length) {
    console.error(`[spike] NOT REPRODUCIBLE: ${problems.join(', ')} differ from a fresh build of the .wat source. Run: npm run build:wasm`);
    process.exit(1);
  }
  console.log(`[spike] wasm artifacts reproducible: ${bytes.length} bytes, sha256 ${sha256}`);
} else {
  writeFileSync(wasmPath, bytes);
  writeFileSync(bytesModulePath, bytesModule);
  console.log(`[spike] built dsp/gain_biquad.wasm: ${bytes.length} bytes, sha256 ${sha256}`);
}
